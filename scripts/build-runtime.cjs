// Preserve classic-script order; generated bundles are reproducible from editable sources.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex').slice(0, 16);
const common = ['font-size.js','motion.js','demo-access.js','sales-dialogue.js','home-replies.js','chat-engine.js','attachments.js','dialogue-understanding.js','chat-session.js'];
const groups = {
  home: ['font-size.js','motion.js','voice-input.js',...common.slice(2),'voice-understanding.js','app.js','home-ip.js'],
  chat: [...common,'voice-input.js','voice-understanding.js','app.js'],
};
const versions = {};
for (const [name, sources] of Object.entries(groups)) {
  const parts = sources.map(file => {
    const source = fs.readFileSync(path.join(root, file), 'utf8');
    new Function(source);
    return `\n/* Source: ${file} */\n${source}\n;`;
  });
  const bundle = '// Generated by scripts/build-runtime.cjs. Edit source files, then rebuild.\n'+parts.join('\n');
  new Function(bundle);
  const file = `runtime-${name}.js`;
  fs.writeFileSync(path.join(root,file),bundle);
  versions[name] = `${file}?v=${hash(bundle)}`;
}
const css = `styles.css?v=${hash(fs.readFileSync(path.join(root,'styles.css')))}`;
for (const file of fs.readdirSync(root).filter(file => file.endsWith('.html'))) {
  const full = path.join(root,file);
  let html = fs.readFileSync(full,'utf8');
  html = html.replace(/styles\.css\?v=[^"']+/g,css);
  if (['index.html','input.html','conversation.html'].includes(file)) {
    const name = file === 'conversation.html' ? 'chat' : 'home';
    const marker = '<script>DemoStartup.watch()</script>';
    const start = html.indexOf(marker);
    if (start < 0) throw Error(`Missing startup guard: ${file}`);
    const end = html.indexOf('</body>',start);
    const tail = html.slice(start+marker.length,end);
    const actual = [...tail.matchAll(/<script src="([^"?]+)/g)].map(match=>match[1]);
    const expected = groups[name];
    if (!(actual.length===1 && actual[0]===`runtime-${name}.js`) && JSON.stringify(actual)!==JSON.stringify(expected)) throw Error(`Unexpected script order: ${file}`);
    html = html.slice(0,start)+marker+`<script src="${versions[name]}"></script>`+html.slice(end);
    html = html.replace(/<link rel="preload" as="script" data-runtime-preload[^>]*>/g,'');
    html = html.replace('</head>',`<link rel="preload" as="script" data-runtime-preload href="${versions[name]}"></head>`);
  }
  if(html!==fs.readFileSync(full,'utf8'))fs.writeFileSync(full,html);
}
console.log('Runtime bundles and content-based cache versions generated.');
